import type { HttpKeyValue } from './httpCollections'

interface HttpAiExportInput {
  evidence: {
    testDate: string
    environment: string
    service: string
    commitId: string
    notes: string
  }
  method: string
  url: string
  timeoutMs: number
  query: HttpKeyValue[]
  requestHeaders: HttpKeyValue[]
  bodyType: string
  requestBody: string
  response: {
    status: number
    statusText: string
    headers: HttpKeyValue[]
    body: string
    durationMs: number
    sizeBytes: number
    finalUrl: string
    truncated: boolean
    error?: string | null
  }
  exportedAt?: string
}

const REDACTED = '[REDACTED]'
const SENSITIVE_KEY = /authorization|cookie|token|api[-_]?key|secret|password|passwd|session|credential/i

function redactValue(value: unknown, key = ''): unknown {
  if (SENSITIVE_KEY.test(key))
    return REDACTED
  if (Array.isArray(value))
    return value.map(item => redactValue(item))
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([childKey, childValue]) => [childKey, redactValue(childValue, childKey)]),
    )
  }
  return value
}

function redactRows(rows: HttpKeyValue[]) {
  return rows
    .filter(row => row.enabled && row.key.trim())
    .map(row => ({
      key: row.key,
      value: SENSITIVE_KEY.test(row.key) ? REDACTED : row.value,
    }))
}

function redactUrl(rawUrl: string) {
  try {
    const parsed = new URL(rawUrl)
    for (const key of parsed.searchParams.keys()) {
      if (SENSITIVE_KEY.test(key))
        parsed.searchParams.set(key, REDACTED)
    }
    return parsed.toString()
  }
  catch {
    return rawUrl.replace(
      /([?&](?:authorization|token|access_token|api[-_]?key|secret|password|passwd|session|credential)=)[^&#]*/gi,
      `$1${REDACTED}`,
    )
  }
}

function redactStructuredText(value: string, bodyType = '') {
  if (!value.trim())
    return ''
  try {
    return JSON.stringify(redactValue(JSON.parse(value)), null, 2)
  }
  catch {
    if (bodyType === 'form') {
      const form = new URLSearchParams(value)
      for (const key of form.keys()) {
        if (SENSITIVE_KEY.test(key))
          form.set(key, REDACTED)
      }
      return form.toString()
    }
    return value.replace(
      /\b(authorization|token|access_token|api[-_]?key|secret|password|passwd|session|credential)(\s*[:=]\s*)([^\s&,;]+)/gi,
      `$1$2${REDACTED}`,
    )
  }
}

function codeBlock(value: string, language = '') {
  const fence = value.includes('```') ? '````' : '```'
  return `${fence}${language}\n${value || '(empty)'}\n${fence}`
}

export function buildHttpAiContext(input: HttpAiExportInput) {
  const requestHeaders = redactRows(input.requestHeaders)
  const responseHeaders = redactRows(input.response.headers)
  const query = redactRows(input.query)
  const requestBody = redactStructuredText(input.requestBody, input.bodyType)
  const responseBody = redactStructuredText(input.response.body)
  const usedLoginToken = input.requestHeaders.some(row => (
    row.enabled
    && Boolean(row.value.trim())
    && /authorization|token/i.test(row.key)
  ))

  return [
    '# HTTP Integration Evidence',
    '',
    '> Generated by Toolbox for AI-assisted debugging and integration verification. Sensitive headers, URL parameters, and JSON fields are redacted automatically.',
    '',
    `- Exported at: ${input.exportedAt ?? new Date().toISOString()}`,
    `- Test date: ${input.evidence.testDate}`,
    `- Deployment environment: ${input.evidence.environment}`,
    `- Service / repository: ${input.evidence.service}`,
    `- Deployment commit: ${input.evidence.commitId}`,
    `- Authentication: ${usedLoginToken ? 'Real login token was used; the token value is intentionally omitted.' : 'No login token header was recorded.'}`,
    '',
    '## Evidence Notes',
    '',
    input.evidence.notes || '(none)',
    '',
    '## Request Summary',
    '',
    `- Method: ${input.method}`,
    `- Request URL: ${redactUrl(input.url)}`,
    `- Timeout: ${input.timeoutMs} ms`,
    '',
    '## Request Query',
    '',
    codeBlock(JSON.stringify(query, null, 2), 'json'),
    '',
    '## Request Headers',
    '',
    codeBlock(JSON.stringify(requestHeaders, null, 2), 'json'),
    '',
    `## Request Body (${input.bodyType})`,
    '',
    codeBlock(requestBody, input.bodyType === 'json' ? 'json' : 'text'),
    '',
    '## Response Summary',
    '',
    `- Status: ${input.response.status || 'ERROR'} ${input.response.statusText}`,
    `- Duration: ${input.response.durationMs} ms`,
    `- Size: ${input.response.sizeBytes} bytes`,
    `- Final URL: ${redactUrl(input.response.finalUrl)}`,
    `- Truncated: ${input.response.truncated ? 'yes' : 'no'}`,
    `- Error: ${input.response.error || 'none'}`,
    '',
    '## Response Headers',
    '',
    codeBlock(JSON.stringify(responseHeaders, null, 2), 'json'),
    '',
    '## Response Body',
    '',
    codeBlock(responseBody, 'json'),
    '',
  ].join('\n')
}

export function httpAiExportFilename(rawUrl: string) {
  let endpoint = 'request'
  try {
    const parsed = new URL(rawUrl)
    endpoint = parsed.pathname.split('/').filter(Boolean).at(-1) || parsed.hostname
  }
  catch {
    // Use the generic fallback for incomplete URLs.
  }
  const safeEndpoint = endpoint.replace(/[^\w-]+/g, '-').replace(/^-+|-+$/g, '') || 'request'
  const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19)
  return `http-${safeEndpoint}-${timestamp}.md`
}
